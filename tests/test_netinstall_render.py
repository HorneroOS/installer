"""Netinstall groups are catalogue-generated, unticked and honest."""
from __future__ import annotations

import importlib.util
import os
from pathlib import Path

import pytest
import yaml

ROOT = Path(__file__).resolve().parents[1]
PRODUCT = Path(os.environ.get("HORNEROS_PRODUCT_SOURCE", "/tmp/hornero-main"))
CONF = ROOT / "image" / "calamares" / "modules" / "netinstall.conf"


def _doc() -> dict:
    return yaml.safe_load(CONF.read_text(encoding="utf-8"))


def _leaves(items):
    for item in items:
        if item.get("subgroups"):
            yield from _leaves(item["subgroups"])
        else:
            yield item


def _all_packages(items):
    return [pkg for leaf in _leaves(items) for pkg in leaf.get("packages", [])]


def test_netinstall_is_local_optional_and_unticked_by_default():
    doc = _doc()
    assert doc["groupsUrl"] == "local"
    assert doc["required"] is False
    assert doc["groups"]
    for item in _walk(doc["groups"]):
        assert item.get("selected") is not True, item["name"]
        assert item.get("critical") is not True, item["name"]


def _walk(items):
    for item in items:
        yield item
        yield from _walk(item.get("subgroups", []))


def test_no_base_kernel_or_bootloader_packages_offered():
    packages = set(_all_packages(_doc()["groups"]))
    assert not packages & {
        "base", "linux", "linux-lts", "linux-zen", "linux-hardened",
        "grub", "efibootmgr", "linux-firmware",
    }


def test_proprietary_only_as_explicit_individual_items():
    doc = _doc()
    for leaf in _leaves(doc["groups"]):
        packages = set(leaf.get("packages", []))
        if packages & {"reaper", "steam"}:
            assert packages <= {"reaper", "steam"}, leaf["name"]
            assert "(proprietary)" in leaf["name"]
            assert "licence" in leaf["description"] or "license" in leaf["description"]


def test_manual_and_reference_only_applications_never_appear():
    text = CONF.read_text(encoding="utf-8")
    assert "artcraft" not in text
    packages = set(_all_packages(_doc()["groups"]))
    assert "penpot" not in packages
    assert "heroic-games-launcher" not in packages


def test_groups_cover_studio_gaming_capabilities_and_individuals():
    names = [g["name"] for g in _doc()["groups"]]
    assert "Studio specializations" in names
    assert "Gaming" in names
    assert "Capabilities" in names
    assert "Individual applications" in names
    leaves = list(_leaves(_doc()["groups"]))
    assert len(leaves) >= 20
    assert all(leaf.get("packages") for leaf in leaves)


@pytest.mark.skipif(
    not (PRODUCT / "editions" / "catalogue.yaml").exists(),
    reason="canonical Hornero product source not available",
)
def test_render_matches_committed_netinstall_conf(tmp_path):
    spec = importlib.util.spec_from_file_location(
        "render_netinstall", ROOT / "scripts" / "render-netinstall.py"
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    catalogue = yaml.safe_load(
        (PRODUCT / "editions" / "catalogue.yaml").read_text(encoding="utf-8")
    )
    rendered = module.render(PRODUCT, catalogue)
    regenerated = tmp_path / "netinstall.conf"
    lock = yaml.safe_load((ROOT / "installer.lock.yaml").read_text(encoding="utf-8"))
    header = (
        "# Generated by scripts/render-netinstall.py from the pinned\n"
        f"# HorneroOS/hornero catalogue ({lock['product']['revision']}); do not edit.\n"
        "# All groups are unticked by default, except open-source GPU groups\n"
        "# pre-selected from a PCI probe at render time. GPU groups are absent\n"
        "# when the pinned catalogue ships no gpuVendors/gpuProvenance\n"
        "# (dependency: HorneroOS/hornero#466 + a catalogue pin bump).\n"
    )
    regenerated.write_text(
        header + yaml.safe_dump(rendered, sort_keys=False, allow_unicode=True),
        encoding="utf-8",
    )
    assert regenerated.read_text(encoding="utf-8") == CONF.read_text(encoding="utf-8"), (
        "netinstall.conf drifted from the pinned catalogue; "
        "re-run scripts/render-netinstall.py"
    )


@pytest.mark.skipif(
    not (PRODUCT / "editions" / "catalogue.yaml").exists(),
    reason="canonical Hornero product source not available",
)
def test_every_package_comes_from_the_pinned_catalogue():
    catalogue = yaml.safe_load(
        (PRODUCT / "editions" / "catalogue.yaml").read_text(encoding="utf-8")
    )
    allowed: set[str] = set()
    for apps_key in ("studioApplications", "gamingApplications"):
        for app in (catalogue.get(apps_key) or {}).values():
            allowed.update(app.get("packages", []))
    for entry in (catalogue.get("capabilities") or {}).values():
        allowed.update(entry.get("packages", []))
    allowed.update(catalogue.get("studioPlatformPackages", []))
    allowed.update(catalogue.get("gamingPlatformPackages", []))
    allowed.update((catalogue.get("gpuProvenance") or {}).keys())
    # Resolver platform sets (pipewire stack, vulkan loaders, ...) are
    # plain package lists somewhere in the catalogue document.
    def collect(node):
        if isinstance(node, list) and node and all(isinstance(x, str) for x in node):
            allowed.update(node)
        elif isinstance(node, dict):
            for value in node.values():
                collect(value)
        elif isinstance(node, list):
            for value in node:
                collect(value)
    collect(catalogue)
    unknown = set(_all_packages(_doc()["groups"])) - allowed
    assert not unknown, f"packages outside the pinned catalogue: {sorted(unknown)}"


